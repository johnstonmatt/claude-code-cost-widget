/** Enable or disable the widget for one Claude Code configuration directory. */
import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { mkdir, readFile, rename, rm, rmdir, writeFile } from "node:fs/promises";
import { isAbsolute, join } from "node:path";
import {
  installStatusLine,
  isWidgetStatusLine,
  shellQuote,
  uninstallStatusLine,
} from "./settings.js";

const FILES = ["format.mjs", "statusline.mjs"];
const LAUNCHER = "statusline.sh";
const SMOKE_INPUT = '{"cost":{"total_cost_usd":0.01234}}';
const SMOKE_OUTPUT =
  "Claude session estimate $0.01234 | latest response unavailable";

export function claudeConfigDirectory(env = process.env) {
  const directory = env.CLAUDE_CONFIG_DIR ||
    (env.HOME ? join(env.HOME, ".claude") : "");
  if (!isAbsolute(directory)) {
    throw new Error("Set HOME or an absolute CLAUDE_CONFIG_DIR.");
  }
  return directory;
}

/** Stable home for the script, so it outlives the npx cache it came from. */
export function scriptDirectory(directory) {
  return join(directory, "claude-code-cost-widget");
}

export function scriptPath(directory) {
  return join(scriptDirectory(directory), "statusline.mjs");
}

/** What settings.json runs. Its path never changes, so neither does the command. */
export function launcherPath(directory) {
  return join(scriptDirectory(directory), LAUNCHER);
}

/**
 * Prefer the Node binary recorded at enable time, then any node on PATH, so
 * removing or upgrading that Node version doesn't silently blank the footer.
 */
export function launcherScript(node, script) {
  return `#!/bin/sh
# Generated by \`claude-code-cost-widget enable\`; rerun it to regenerate.
for node in ${shellQuote(node)} "$(command -v node 2>/dev/null)"; do
  if [ -n "$node" ] && [ -x "$node" ]; then
    exec "$node" ${shellQuote(script)}
  fi
done
echo "Cost widget: Node.js not found. Run: npx claude-code-cost-widget enable"
`;
}

/** Atomically write `content` unless the file already has it. */
async function writeIfChanged(path, content) {
  const existing = await readFile(path, "utf8").catch((error) => {
    if (error.code === "ENOENT") return undefined;
    throw error;
  });
  if (existing === content) return false;
  const temporary = `${path}.${randomBytes(6).toString("hex")}`;
  try {
    await writeFile(temporary, content, { flag: "wx" });
    await rename(temporary, path);
  } finally {
    await rm(temporary, { force: true });
  }
  return true;
}

async function copyScripts(directory) {
  const destination = scriptDirectory(directory);
  await mkdir(destination, { recursive: true });
  let changed = false;
  for (const name of FILES) {
    const source = await readFile(new URL(name, import.meta.url), "utf8");
    changed = await writeIfChanged(join(destination, name), source) || changed;
  }
  return changed;
}

/** Run a launcher exactly as Claude Code will: through sh, payload on stdin. */
function smokeTest(launcher) {
  const smoke = spawnSync("/bin/sh", [launcher], {
    input: SMOKE_INPUT,
    encoding: "utf8",
    timeout: 10_000,
  });
  return smoke.status === 0 && smoke.stdout.trim() === SMOKE_OUTPUT;
}

async function removeScripts(directory) {
  for (const name of [...FILES, LAUNCHER]) {
    await rm(join(scriptDirectory(directory), name), { force: true });
  }
  // Leave the directory alone if anything else was put in it.
  await rmdir(scriptDirectory(directory)).catch((error) => {
    if (!["ENOENT", "ENOTEMPTY", "EEXIST"].includes(error.code)) throw error;
  });
}

export async function enable(directory, { node = process.execPath } = {}) {
  let changed = await copyScripts(directory);
  const launcher = launcherPath(directory);
  // Test a candidate first so a bad Node path can't replace a working launcher.
  const candidate = `${launcher}.${randomBytes(6).toString("hex")}`;
  const content = launcherScript(node, scriptPath(directory));
  try {
    await writeFile(candidate, content, { flag: "wx" });
    if (!smokeTest(candidate)) {
      throw new Error(
        "Status-line smoke test failed; settings were not changed.",
      );
    }
  } finally {
    await rm(candidate, { force: true });
  }
  changed = await writeIfChanged(launcher, content) || changed;
  const command = ["/bin/sh", launcher].map(shellQuote).join(" ");
  const result = await installStatusLine(directory, command, owned(directory));
  return { ...result, changed: result.changed || changed };
}

/** Commands this widget wrote: the launcher, and the pre-launcher command that
 * ran statusline.mjs with an absolute Node path. */
function owned(directory) {
  return [launcherPath(directory), scriptPath(directory)];
}

export async function disable(directory) {
  const script = owned(directory);
  const result = await uninstallStatusLine(directory, script);
  const settings = JSON.parse(
    await readFile(result.settings, "utf8").catch((error) => {
      if (error.code === "ENOENT") return "{}";
      throw error;
    }),
  );
  if (!isWidgetStatusLine(settings.statusLine, script)) {
    await removeScripts(directory);
  }
  return result;
}
